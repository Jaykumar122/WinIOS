static void test_pycrypto_reference_vectors() {
    std::cout << "[Stage 234.2] Test 1: Cross-Verification with Python cryptography (OpenSSL backend)...\n";

    for (const auto& vec : kPyCryptoVectors) {
        std::cout << "  Testing vector #" << vec.idx << " (len " << vec.len << ")...\n";
        Ed25519Seed seed{};
        TEST_ASSERT(Ed25519::from_hex(vec.seed_hex, seed.data(), seed.size()), "Parse seed hex");

        Ed25519PublicKey pub{};
        Ed25519PrivateKey priv{};
        Ed25519::create_keypair(pub, priv, seed);

        // 1. Verify Public Key derivation bit-for-bit matches Python's derivation
        std::string derived_pub_hex = Ed25519::to_hex(pub.data(), pub.size());
        TEST_ASSERT(derived_pub_hex == vec.pub_hex, "Public key derivation bit-for-bit equivalence");

        // 2. Decode message
        std::vector<std::uint8_t> msg(vec.len);
        if (vec.len > 0) {
            if (vec.idx == 7) {
                std::fill(msg.begin(), msg.end(), static_cast<std::uint8_t>(0xFF));
            } else if (vec.idx == 8) {
                std::fill(msg.begin(), msg.end(), static_cast<std::uint8_t>(0x00));
            } else {
                TEST_ASSERT(Ed25519::from_hex(vec.msg_hex, msg.data(), msg.size()), "Parse message hex");
            }
        }

        // 3. Decode Python's signature and verify with WinIOS Ed25519::verify
        Ed25519Signature py_sig{};
        TEST_ASSERT(Ed25519::from_hex(vec.sig_hex, py_sig.data(), py_sig.size()), "Parse sig hex");
        TEST_ASSERT(Ed25519::verify(py_sig, msg.data(), msg.size(), pub), "WinIOS verifies Python signature");

        // 4. Generate signature with WinIOS Ed25519::sign and check bit-for-bit identity
        Ed25519Signature winios_sig{};
        Ed25519::sign(winios_sig, msg.data(), msg.size(), pub, priv);
        std::string winios_sig_hex = Ed25519::to_hex(winios_sig.data(), winios_sig.size());
        TEST_ASSERT(winios_sig_hex == vec.sig_hex, "WinIOS signature matches Python signature bit-for-bit");

        // 5. Corrupted signature bit-flip must fail
        Ed25519Signature bad_sig = py_sig;
        bad_sig[0] ^= 0x01;
        TEST_ASSERT(!Ed25519::verify(bad_sig, msg.data(), msg.size(), pub), "Corrupted signature rejected");

        // 6. Corrupted public key bit-flip must fail
        Ed25519PublicKey bad_pub = pub;
        bad_pub[0] ^= 0x01;
        TEST_ASSERT(!Ed25519::verify(py_sig, msg.data(), msg.size(), bad_pub), "Corrupted public key rejected");
    }
    std::cout << "  -> 10/10 Python cryptography reference vectors verified successfully in both directions.\n";
}

static void test_winios_dynamic_keypair_and_sign() {
    std::cout << "[Stage 234.2] Test 2: WinIOS Dynamic Key Generation & Signature Correctness...\n";

    for (int i = 0; i < 10; ++i) {
        Ed25519PublicKey pub{};
        Ed25519PrivateKey priv{};
        TEST_ASSERT(Ed25519::generate_keypair(pub, priv), "Generate dynamic keypair");

        std::string msg = "Dynamic test message #" + std::to_string(i);
        Ed25519Signature sig{};
        Ed25519::sign(sig, msg.data(), msg.size(), pub, priv);

        TEST_ASSERT(Ed25519::verify(sig, msg.data(), msg.size(), pub), "Verify dynamically signed message");

        // Check scalar S < L
        // S is the second 32 bytes of the signature: sig[32..63]
        // L = 2^252 + 27742317777372353535851937790883648493
        // The highest byte of L is 0x10. If sig[63] > 0x10, it definitely exceeds L.
        TEST_ASSERT(sig[63] <= 0x10, "Signature scalar S bounded by group order L");
    }
    std::cout << "  -> 10/10 dynamic keypair generation and verification rounds passed.\n";
}

