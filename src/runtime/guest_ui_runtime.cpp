void GuestUiRuntime::draw_char_8x8(
    std::uint8_t* buffer,
    std::uint32_t width,
    std::uint32_t height,
    std::uint32_t stride,
    graphics::PixelFormat fmt,
    std::int32_t x,
    std::int32_t y,
    char c,
    std::uint32_t color,
    std::uint32_t scale) noexcept {

    if (!buffer || width == 0 || height == 0 || scale == 0) return;
    if (c < 32 || c > 126) c = '?';

    const std::uint8_t* glyph = kFont8x8[static_cast<std::size_t>(c - 32)];

    for (std::uint32_t row = 0; row < 8; ++row) {
        std::uint8_t row_bits = glyph[row];
        for (std::uint32_t col = 0; col < 8; ++col) {
            if ((row_bits & (0x80u >> col)) != 0) {
                std::int32_t px = x + static_cast<std::int32_t>(col * scale);
                std::int32_t py = y + static_cast<std::int32_t>(row * scale);
                if (px >= 0 && py >= 0 &&
                    static_cast<std::uint32_t>(px) < width &&
                    static_cast<std::uint32_t>(py) < height) {

                    graphics::Rect pixel_rect{
                        static_cast<std::uint32_t>(px),
                        static_cast<std::uint32_t>(py),
                        scale,
                        scale
                    };

                    graphics::RasterPrimitives::fill_rect(
                        buffer, width, height, stride, fmt, pixel_rect, color);
                }
            }
        }
    }
}

void GuestUiRuntime::draw_string_8x8(
    std::uint8_t* buffer,
    std::uint32_t width,
    std::uint32_t height,
    std::uint32_t stride,
    graphics::PixelFormat fmt,
    std::int32_t x,
    std::int32_t y,
    const char* text,
    std::uint32_t color,
    std::uint32_t scale) noexcept {

    if (!text) return;

    std::int32_t cur_x = x;
    std::int32_t cur_y = y;
    std::int32_t char_advance = static_cast<std::int32_t>(8 * scale + scale); // 1 pixel spacing

    while (*text) {
        char ch = *text++;
        if (ch == '\n') {
            cur_x = x;
            cur_y += static_cast<std::int32_t>(10 * scale);
            continue;
        }

        draw_char_8x8(buffer, width, height, stride, fmt, cur_x, cur_y, ch, color, scale);
        cur_x += char_advance;
    }
}

void GuestUiRuntime::draw_button(
    std::uint8_t* buffer,
    std::uint32_t width,
    std::uint32_t height,
    std::uint32_t stride,
    graphics::PixelFormat fmt,
    const graphics::Rect& frame,
    const char* label,
    std::uint32_t bg_color,
    std::uint32_t text_color,
    bool is_pressed) noexcept {

    if (!buffer || frame.empty()) return;

    // Background
    std::uint32_t effective_bg = is_pressed ? 0xFF0055AA : bg_color;
    graphics::RasterPrimitives::fill_rect(buffer, width, height, stride, fmt, frame, effective_bg);

    // 3D outline (top/left lighter, bottom/right darker)
    std::uint32_t border_hi = 0xFFFFFFFF;
    std::uint32_t border_lo = 0xFF222222;

    graphics::Rect top_border{frame.x, frame.y, frame.width, 2};
    graphics::Rect left_border{frame.x, frame.y, 2, frame.height};
    graphics::Rect bottom_border{frame.x, frame.y + frame.height - 2, frame.width, 2};
    graphics::Rect right_border{frame.x + frame.width - 2, frame.y, 2, frame.height};

    graphics::RasterPrimitives::fill_rect(buffer, width, height, stride, fmt, top_border, is_pressed ? border_lo : border_hi);
    graphics::RasterPrimitives::fill_rect(buffer, width, height, stride, fmt, left_border, is_pressed ? border_lo : border_hi);
    graphics::RasterPrimitives::fill_rect(buffer, width, height, stride, fmt, bottom_border, is_pressed ? border_hi : border_lo);
    graphics::RasterPrimitives::fill_rect(buffer, width, height, stride, fmt, right_border, is_pressed ? border_hi : border_lo);

    // Center text
    if (label) {
        std::size_t len = std::strlen(label);
        std::uint32_t text_w = static_cast<std::uint32_t>(len * 9 * 2); // scale 2
        std::uint32_t text_h = 16;

        std::int32_t tx = static_cast<std::int32_t>(frame.x + (frame.width > text_w ? (frame.width - text_w) / 2 : 4));
        std::int32_t ty = static_cast<std::int32_t>(frame.y + (frame.height > text_h ? (frame.height - text_h) / 2 : 4));

        if (is_pressed) {
            tx += 1;
            ty += 1;
        }

        draw_string_8x8(buffer, width, height, stride, fmt, tx, ty, label, text_color, 2);
    }
}

void GuestUiRuntime::draw_app_icon(
    std::uint8_t* buffer,
    std::uint32_t width,
    std::uint32_t height,
    std::uint32_t stride,
    graphics::PixelFormat fmt,
    const graphics::Rect& frame,
    const char* label,
    std::uint32_t icon_color) noexcept {

    if (!buffer || frame.empty()) return;

    // Fill icon squircle body
    graphics::RasterPrimitives::fill_rect(buffer, width, height, stride, fmt, frame, icon_color);

    // Bevel highlights
    graphics::Rect highlight{frame.x + 4, frame.y + 4, frame.width - 8, 4};
    graphics::RasterPrimitives::fill_rect(buffer, width, height, stride, fmt, highlight, 0x66FFFFFF);

    // Centered label underneath icon
    if (label) {
        std::size_t len = std::strlen(label);
        std::uint32_t text_w = static_cast<std::uint32_t>(len * 9 * 2);
        std::int32_t lx = static_cast<std::int32_t>(frame.x + (frame.width > text_w ? (frame.width - text_w) / 2 : 0));
        std::int32_t ly = static_cast<std::int32_t>(frame.y + frame.height + 12);

        draw_string_8x8(buffer, width, height, stride, fmt, lx, ly, label, 0xFFFFFFFF, 2);
    }
}

void GuestUiRuntime::draw_status_bar(
    std::uint8_t* buffer,
    std::uint32_t width,
    std::uint32_t height,
    std::uint32_t stride,
    graphics::PixelFormat fmt,
    const char* time_str,
    std::uint32_t battery_pct) noexcept {

    if (!buffer || width == 0 || height == 0) return;

    // Top status bar banner (e.g. 54px high)
    graphics::Rect bar_rect{0, 0, width, 54};
    graphics::RasterPrimitives::fill_rect(buffer, width, height, stride, fmt, bar_rect, 0xFF050508);

    // Dynamic Island notch pill
    std::uint32_t notch_w = 260;
    std::uint32_t notch_h = 42;
    graphics::Rect notch{(width - notch_w) / 2, 8, notch_w, notch_h};
    graphics::RasterPrimitives::fill_rect(buffer, width, height, stride, fmt, notch, 0xFF000000);

    // Clock string on the left
    if (time_str) {
        draw_string_8x8(buffer, width, height, stride, fmt, 48, 18, time_str, 0xFFFFFFFF, 2);
    }

    // Battery percentage on the right
    char b_buf[16];
    std::snprintf(b_buf, sizeof(b_buf), "%u%%", std::min(battery_pct, 100u));
    draw_string_8x8(buffer, width, height, stride, fmt, static_cast<std::int32_t>(width - 120), 18, b_buf, 0xFF34C759, 2);
}

