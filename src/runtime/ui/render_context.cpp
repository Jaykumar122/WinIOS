RenderContext::RenderContext(std::uint8_t* buffer, std::uint32_t width, std::uint32_t height, std::uint32_t stride)
    : buffer_(buffer), width_(width), height_(height), stride_(stride) {
    clip_stack_.push_back({0, 0, static_cast<std::int32_t>(width), static_cast<std::int32_t>(height)});
}

void RenderContext::push_clip(const Rect& clip) {
    Rect current = current_clip();
    clip_stack_.push_back(current.intersect_with(clip));
}

void RenderContext::pop_clip() {
    if (clip_stack_.size() > 1) {
        clip_stack_.pop_back();
    }
}

Rect RenderContext::current_clip() const noexcept {
    if (clip_stack_.empty()) {
        return {0, 0, static_cast<std::int32_t>(width_), static_cast<std::int32_t>(height_)};
    }
    return clip_stack_.back();
}

void RenderContext::invalidate(const Rect& dirty) {
    if (dirty.width <= 0 || dirty.height <= 0) return;
    if (!has_damage_) {
        dirty_bounds_ = dirty;
        has_damage_ = true;
    } else {
        dirty_bounds_ = dirty_bounds_.union_with(dirty);
    }
}

void RenderContext::clear_damage() noexcept {
    has_damage_ = false;
    dirty_bounds_ = {0, 0, 0, 0};
}

void RenderContext::set_pixel_clipped(std::int32_t x, std::int32_t y, std::uint32_t color_bgra) {
    if (!buffer_) return;
    Rect clip = current_clip();
    if (!clip.contains(x, y)) return;
    if (x < 0 || y < 0 || x >= static_cast<std::int32_t>(width_) || y >= static_cast<std::int32_t>(height_)) return;

    auto* row = reinterpret_cast<std::uint32_t*>(buffer_ + static_cast<std::size_t>(y) * stride_);
    row[x] = color_bgra;
}

void RenderContext::fill_rect(const Rect& r, std::uint32_t color_bgra) {
    if (!buffer_ || r.width <= 0 || r.height <= 0) return;
    Rect clipped = r.intersect_with(current_clip());
    if (clipped.width <= 0 || clipped.height <= 0) return;

    invalidate(clipped);

    for (std::int32_t py = clipped.y; py < clipped.y + clipped.height; ++py) {
        auto* row = reinterpret_cast<std::uint32_t*>(buffer_ + static_cast<std::size_t>(py) * stride_);
        for (std::int32_t px = clipped.x; px < clipped.x + clipped.width; ++px) {
            row[px] = color_bgra;
        }
    }
}

void RenderContext::draw_rect_outline(const Rect& r, std::uint32_t color_bgra, std::int32_t thickness) {
    if (thickness <= 0) return;
    fill_rect({r.x, r.y, r.width, thickness}, color_bgra); // Top
    fill_rect({r.x, r.y + r.height - thickness, r.width, thickness}, color_bgra); // Bottom
    fill_rect({r.x, r.y, thickness, r.height}, color_bgra); // Left
    fill_rect({r.x + r.width - thickness, r.y, thickness, r.height}, color_bgra); // Right
}

void RenderContext::draw_rounded_rect(const Rect& r, std::int32_t radius, std::uint32_t color_bgra) {
    if (radius <= 0) {
        fill_rect(r, color_bgra);
        return;
    }
    std::int32_t rad = std::min({radius, r.width / 2, r.height / 2});
    // Center block
    fill_rect({r.x + rad, r.y, r.width - 2 * rad, r.height}, color_bgra);
    // Left & Right blocks
    fill_rect({r.x, r.y + rad, rad, r.height - 2 * rad}, color_bgra);
    fill_rect({r.x + r.width - rad, r.y + rad, rad, r.height - 2 * rad}, color_bgra);

    // Rounded 4 corners
    for (std::int32_t dy = 0; dy < rad; ++dy) {
        for (std::int32_t dx = 0; dx < rad; ++dx) {
            std::int32_t dist_sq = (rad - dx) * (rad - dx) + (rad - dy) * (rad - dy);
            if (dist_sq <= rad * rad) {
                set_pixel_clipped(r.x + dx, r.y + dy, color_bgra); // Top-left
                set_pixel_clipped(r.x + r.width - 1 - dx, r.y + dy, color_bgra); // Top-right
                set_pixel_clipped(r.x + dx, r.y + r.height - 1 - dy, color_bgra); // Bottom-left
                set_pixel_clipped(r.x + r.width - 1 - dx, r.y + r.height - 1 - dy, color_bgra); // Bottom-right
            }
        }
    }
    invalidate(r.intersect_with(current_clip()));
}

void RenderContext::draw_line(std::int32_t x0, std::int32_t y0, std::int32_t x1, std::int32_t y1, std::uint32_t color_bgra) {
    std::int32_t dx = std::abs(x1 - x0);
    std::int32_t dy = -std::abs(y1 - y0);
    std::int32_t sx = (x0 < x1) ? 1 : -1;
    std::int32_t sy = (y0 < y1) ? 1 : -1;
    std::int32_t err = dx + dy;

    while (true) {
        set_pixel_clipped(x0, y0, color_bgra);
        if (x0 == x1 && y0 == y1) break;
        std::int32_t e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

void RenderContext::draw_char(std::int32_t x, std::int32_t y, char c, std::uint32_t color_bgra, std::uint32_t scale) {
    if (scale == 0) scale = 1;
    if (static_cast<unsigned char>(c) < 32 || static_cast<unsigned char>(c) > 126) {
        c = '?';
    }
    const auto* glyph = kFont8x8[static_cast<std::size_t>(c - 32)];

    for (std::uint32_t row = 0; row < 8; ++row) {
        const std::uint8_t bits = glyph[row];
        for (std::uint32_t col = 0; col < 8; ++col) {
            if ((bits & (1u << (7u - col))) != 0) {
                for (std::uint32_t sy = 0; sy < scale; ++sy) {
                    for (std::uint32_t sx = 0; sx < scale; ++sx) {
                        set_pixel_clipped(x + static_cast<std::int32_t>(col * scale + sx),
                                          y + static_cast<std::int32_t>(row * scale + sy),
                                          color_bgra);
                    }
                }
            }
        }
    }
}

void RenderContext::draw_string(std::int32_t x, std::int32_t y, const char* text, std::uint32_t color_bgra, std::uint32_t scale) {
    if (!text) return;
    std::int32_t cur_x = x;
    std::int32_t cur_y = y;
    while (*text != '\0') {
        if (*text == '\n') {
            cur_x = x;
            cur_y += static_cast<std::int32_t>(8 * scale + 2);
        } else {
            draw_char(cur_x, cur_y, *text, color_bgra, scale);
            cur_x += static_cast<std::int32_t>(8 * scale);
        }
        ++text;
    }
}

