#pragma once

#include <cstdint>
#include <string>

namespace winios::input {

// -----------------------------------------------------------------------------
// Input Provenance: Categorization of event source origin
// -----------------------------------------------------------------------------
enum class InputProvenance : std::uint8_t {
    PhysicalWindowsInput   = 0, // Genuine hardware mouse/keyboard received via Win32 message loop
    WindowsMessageInjected = 1, // Synthetic Win32 message injected via SendMessage/PostMessage
    TestInjected           = 2, // Programmatic test harness injection via test framework API
    GuestGenerated         = 3, // Generated by a guest process via Category C IPC / dispatch
    SyntheticHostEvent     = 4  // Generated internally by host subsystem (e.g. focus auto-blur, window-close)
};

[[nodiscard]] inline const char* input_provenance_to_string(InputProvenance p) noexcept {
    switch (p) {
    case InputProvenance::PhysicalWindowsInput:   return "PhysicalWindowsInput";
    case InputProvenance::WindowsMessageInjected: return "WindowsMessageInjected";
    case InputProvenance::TestInjected:           return "TestInjected";
    case InputProvenance::GuestGenerated:         return "GuestGenerated";
    case InputProvenance::SyntheticHostEvent:     return "SyntheticHostEvent";
    default:                                      return "UnknownProvenance";
    }
}

// -----------------------------------------------------------------------------
// Input Delivery Status: Outcome of event routing and queueing
// -----------------------------------------------------------------------------
enum class InputDeliveryStatus : std::uint8_t {
    Delivered               = 0, // Successfully queued and delivered to target window / process
    DroppedQueueFull        = 1, // Queue capacity reached and dropped according to drop policy
    RejectedNoTargetWindow  = 2, // Hit testing found no valid window under cursor
    RejectedProcessMismatch = 3, // Target window belongs to a process different from expected
    RejectedWindowDestroyed = 4, // Window was closed or destroyed before event processing
    RejectedUnauthorized    = 5  // Caller lacks capability or permission for input interaction
};

[[nodiscard]] inline const char* input_delivery_status_to_string(InputDeliveryStatus s) noexcept {
    switch (s) {
    case InputDeliveryStatus::Delivered:               return "Delivered";
    case InputDeliveryStatus::DroppedQueueFull:        return "DroppedQueueFull";
    case InputDeliveryStatus::RejectedNoTargetWindow:  return "RejectedNoTargetWindow";
    case InputDeliveryStatus::RejectedProcessMismatch: return "RejectedProcessMismatch";
    case InputDeliveryStatus::RejectedWindowDestroyed: return "RejectedWindowDestroyed";
    case InputDeliveryStatus::RejectedUnauthorized:    return "RejectedUnauthorized";
    default:                                           return "UnknownDeliveryStatus";
    }
}

// -----------------------------------------------------------------------------
// Input Provenance Telemetry Record: Complete end-to-end trace descriptor
// -----------------------------------------------------------------------------
struct InputProvenanceTelemetry {
    std::uint64_t       sequence_number{0};
    InputProvenance     provenance{InputProvenance::PhysicalWindowsInput};
    std::uint32_t       win32_msg_id{0}; // e.g. WM_MOUSEMOVE, WM_LBUTTONDOWN, WM_KEYDOWN
    std::uint64_t       timestamp_us{0};
    std::uint64_t       host_time_ns{0};
    std::int32_t        screen_x{0};
    std::int32_t        screen_y{0};
    std::int32_t        client_x{0};
    std::int32_t        client_y{0};
    std::int32_t        guest_x{0};
    std::int32_t        guest_y{0};
    std::uint32_t       target_window_id{0};
    std::uint32_t       target_pid{0};
    std::uint32_t       focused_window_id{0};
    std::uint32_t       captured_window_id{0};
    InputDeliveryStatus delivery_status{InputDeliveryStatus::Delivered};
    std::string         rejection_reason;
};

} // namespace winios::input
